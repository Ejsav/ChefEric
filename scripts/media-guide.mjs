#!/usr/bin/env node
// Writes docs/PHOTOGRAPHY_GUIDE.md from content/media.ts: the professional
// shoot brief for every photograph and film slot on the site.
//   npm run media:guide          regenerate
//   npm run media:guide -- --check   fail if the committed guide is stale (CI)
// The site, `npm run media` and this guide all read the same
// manifest, so they cannot disagree about what is needed or where it goes.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const { mediaSlots } = await import(join(root, "content/media.ts"));
const out = join(root, "docs/PHOTOGRAPHY_GUIDE.md");

const sections = [
  ["hero", "Home · the hero", "The first screen. It decides whether a visitor keeps reading."],
  ["portrait", "Home · the chef", "The portrait that introduces the person behind the table."],
  ["exp-", "Experiences", "One image per service, on the home page cards and on /experiences."],
  ["menu-", "Sample menus", "One signature dish per sample menu, beside its printed card (home and /menus)."],
  ["food-", "How a menu is made", "Three images in sequence on /menus: the market, the pass, the table."],
  ["gallery-", "Gallery", "Twelve frames: the first six on the home page, all twelve on /gallery. Mixed ratios, read as a contact sheet."],
  ["room-", "Plan your evening · destinations", "The composer's rooms on the home page and /experiences. The same frames lead the destination pages under /private-dining, cropped to 4:5, so keep the subject centred."],
  ["chapter-", "The Chef · six chapters", "The pinned horizontal story on /chef, one frame per chapter."],
];
const section = (id) => sections.find(([p]) => id.startsWith(p)) ?? sections[0];

const who = { eric: "Chef on camera", hands: "Chef's hands only", none: "No people" };
const prio = { 1: "Essential", 2: "Important", 3: "Completes the set" };
const count = (p) => mediaSlots.filter((s) => s.priority === p).length;
const onCamera = mediaSlots.filter((s) => s.likeness !== "none").length;
const films = mediaSlots.filter((s) => s.kind === "film");
const cell = (t) => String(t).replace(/\|/g, "\\|").replace(/\n/g, " ");

const lines = [];
const w = (s = "") => lines.push(s);

w("# Photography & film guide");
w();
w("<!-- Generated by scripts/media-guide.mjs from content/media.ts. Edit the manifest, then run `npm run media:guide`. -->");
w();
w("This is the brief for the professional photography and film that a finished site is built on. Every frame on the template has a slot; each slot below says what to shoot, where it appears, the shape and size it must be delivered at, who is on camera, and how much it matters.");
w();
w("The demonstration edition fills these slots with imagery created from Eric Jokl's likeness so a client can see the finished standard. **A client's own site is built with real professional photography shot to this guide.**");
w();
w("| | |");
w("|---|---|");
w(`| **Slots** | ${mediaSlots.length} (${mediaSlots.length - films.length} photographs, ${films.length} film${films.length === 1 ? "" : "s"}) |`);
w(`| **Essential** | ${count(1)}: the site should not launch without these |`);
w(`| **Important** | ${count(2)}: shoot on the main day |`);
w(`| **Completes the set** | ${count(3)}: a second half-day, or replace over time |`);
w(`| **Chef on camera** | ${onCamera} frames need the chef or the chef's hands; group them into one session |`);
w();
w("To see which slots are filled and which still show their tonal study, run `npm run media` in the repository. Each slot is listed with the file it expects.");
w();
w("---");
w();
w("## 1. The standard");
w();
w("The reference is the photography of Aman, Nobu Hospitality and Casa Cipriani: editorial, quiet, expensive. It should read as a film still from a beautiful evening, never as a menu photograph or an event recap.");
w();
w("| | Do | Never |");
w("|---|---|---|");
w("| **Light** | One warm practical source as the key (candle, pendant, fire, window at blue hour). Deep falloff into shadow. Shoot at the edges of the day. | Flash, on-camera light, flat overhead light, mixed colour temperatures. |");
w("| **Lens & depth** | Prime lenses (35mm, 50mm, 85mm) wide open, f/1.4–f/2.8. One sharp subject, everything else soft. | Wide-angle distortion, everything in focus, phone portrait mode. |");
w("| **Colour** | Espresso, walnut, ivory linen, aged brass, deep oxblood. Warm but true skin and food. One consistent grade across the series. | Teal-and-orange presets, heavy HDR, oversaturated food, cool fluorescent casts. |");
w("| **Food** | At table height, on ivory china, dark stone, linen or walnut. Real steam, real sauce, a fork or glass for scale. | Overhead flat-lays, piled garnish, glossy styling sprays, plastic props. |");
w("| **People** | The chef, the chef's hands, and guests only as backs, hands, shoulders and blur. | Identifiable guests, posed group shots, stock smiles, staff looking into the lens unless briefed. |");
w("| **Places** | Rooms that feel lived in and private. | House numbers, boat names, tail numbers, logos, recognisable landmarks, anything that identifies a client's home. |");
w();
w("## 2. Delivery");
w();
w("**Photographs**");
w("- Shoot RAW. Deliver a graded, retouched master per slot plus the RAW selects.");
w("- Web master: JPEG at quality 90 (or lossless WebP/AVIF), **sRGB**, long edge 3000px or larger, at the exact ratio listed for the slot. The site generates every smaller size itself.");
w("- File name is the slot id: `public/media/<slot>.jpg`. Nothing else is needed; the next build places it.");
w("- Retouching: clean distractions, keep texture. No skin smoothing, no reshaping food, no added steam.");
w("- Strip location metadata before delivery.");
w();
w("**Films**");
w("- Capture in 4K at 24 or 25 fps on a locked-off tripod or a very slow, motivated move. No handheld shake, no speed ramps.");
w("- Deliver 1920×1080: `<slot>.mp4` (H.264, high profile) and `<slot>.webm` (VP9), **no audio track**, 10–15 seconds, seamless loop (the last frame must cut invisibly to the first). Target under 2 MB each.");
w("- Deliver the first frame as `<slot>-poster.jpg` (the `hero-film-poster` slot for the hero). Visitors on slow connections or with reduced motion only ever see this still.");
w();
w("**Rights**");
w("- Signed model release for the chef and anyone whose hands or back appear.");
w("- Signed property release for every home, yacht, hangar or venue, including permission for web and social use.");
w("- Perpetual, worldwide web and social licence for the client, with credit to the photographer on the privacy page if requested.");
w();
w("## 3. Shot list");
w();
for (const [prefix, title, note] of sections) {
  const slots = mediaSlots.filter((s) => section(s.id)[0] === prefix);
  if (!slots.length) continue;
  w(`### ${title}`);
  w();
  w(note);
  w();
  w("| File | Where it appears | Shape and size | On camera | Priority | What to capture |");
  w("|---|---|---|---|---|---|");
  for (const s of slots) {
    const file = s.kind === "film" ? `\`${s.id}.mp4\` + \`.webm\`` : `\`${s.id}.jpg\``;
    w(`| ${file} | ${cell(s.where)} | ${cell(s.ratio)} | ${who[s.likeness]} | ${prio[s.priority]} | ${cell(s.brief)} |`);
  }
  w();
}
w("## 4. Planning the shoot");
w();
w("Group the list by light, not by page. A typical schedule for one location with the chef present:");
w();
w("| When | Setup | Slots |");
w("|---|---|---|");
const plan = [
  ["Morning, window light", "Kitchen counter: hands, pasta, classes, the market", (s) => /lesson|hands|market|gallery-0[46]|gallery-11/.test(s.id)],
  ["Late afternoon", "Food at the table: every dish, styled and shot in sequence", (s) => /^menu-|gallery-0[1579]|gallery-12|food-table/.test(s.id)],
  ["Golden hour", "Outdoors: lawn, terrace, the water", (s) => /estate|waterfront|abroad|island|yacht|water|distance/.test(s.id)],
  ["Blue hour into night", "Dining room and kitchen by candle and pendant: portraits, the pass, the room, the hero", (s) => /hero|portrait|private-table|occasion|room-residence|penthouse|hangar|chapter-(room|tonight|fire|patience)|gallery-0[238]|gallery-10|food-pass/.test(s.id)],
];
const placed = new Set();
for (const [when, setup, test] of plan) {
  const ids = mediaSlots.filter((s) => !placed.has(s.id) && test(s)).map((s) => (placed.add(s.id), `\`${s.id}\``));
  w(`| ${when} | ${setup} | ${ids.join(", ")} |`);
}
const rest = mediaSlots.filter((s) => !placed.has(s.id)).map((s) => `\`${s.id}\``);
if (rest.length) w(`| Any time | Supplied or studio assets | ${rest.join(", ")} |`);
w();
w("Shoot the **Essential** slots first in every setup. If the day runs short, everything marked *Completes the set* can follow later without the site ever looking unfinished: an empty slot shows a lit, grained study in the same mood, never a grey box.");
w();
w("## 5. Acceptance checklist");
w();
w("Before a frame goes live, it should pass every line:");
w();
w("- [ ] Exactly the ratio listed for its slot, 3000px or more on the long edge, sRGB.");
w("- [ ] One warm key light, deep shadow, no flash, no overhead flat-lay.");
w("- [ ] One sharp subject; the rest falls away.");
w("- [ ] No identifiable guest, no logo, no house number, boat name or tail number.");
w("- [ ] Grade matches the rest of the series side by side.");
w("- [ ] Seen in place on a preview deployment, on desktop **and** a phone; nothing important is cropped by the frame or covered by type.");
w("- [ ] Releases on file.");
w();

const md = lines.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== md) {
    console.error("docs/PHOTOGRAPHY_GUIDE.md is out of date with content/media.ts. Run `npm run media:guide` and commit.");
    process.exit(1);
  }
  console.log("Photography guide is current.");
} else {
  writeFileSync(out, md);
  console.log(`Wrote docs/PHOTOGRAPHY_GUIDE.md (${mediaSlots.length} slots).`);
}
